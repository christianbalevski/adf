#!/usr/bin/env node
/**
 * Generates the daemon API reference from the OpenAPI contract
 * (docs/daemon/openapi.json, the single source of truth):
 *
 *   docs/daemon/api-reference.html  interactive, self-contained (Redoc, inlined)
 *   docs/daemon/api-reference.md    plain Markdown, by tag
 *
 * Both are generated: never edit them, edit openapi.json and run
 * `npm run docs:api`. Output is deterministic (CI regenerates and diffs).
 */

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const specPath = join(root, 'docs/daemon/openapi.json')
const htmlPath = join(root, 'docs/daemon/api-reference.html')
const mdPath = join(root, 'docs/daemon/api-reference.md')
const rel = (p) => relative(root, p).split('\\').join('/')

const spec = JSON.parse(readFileSync(specPath, 'utf8'))
const METHODS = ['get', 'put', 'post', 'delete', 'patch', 'options', 'head']
const BANNER = 'GENERATED by `npm run docs:api` from docs/daemon/openapi.json. Do not edit this file: edit openapi.json and regenerate.'

// --- HTML (Redoc) ---------------------------------------------------------------

function buildHtml() {
  const dir = mkdtempSync(join(tmpdir(), 'adf-api-docs-'))
  try {
    const out = join(dir, 'api-reference.html')
    execFileSync(process.execPath, [
      join(root, 'node_modules/@redocly/cli/bin/cli.js'), 'build-docs', specPath,
      '--output', out, '--title', spec.info.title, '--disableGoogleFont', '--config', join(root, 'redocly.yaml'),
    ], { cwd: root, stdio: ['ignore', 'ignore', 'inherit'] })
    let html = readFileSync(out, 'utf8')

    // Inline the Redoc bundle the page would load from the CDN, after checking
    // it is byte-identical to what the CDN tag pins (SRI hash).
    const tag = /<script src="https:\/\/cdn\.redocly\.com\/redoc\/v([\d.]+)\/bundles\/redoc\.standalone\.js" integrity="(sha384-[^"]+)"[^>]*><\/script>/.exec(html)
    if (!tag) throw new Error('Redoc CDN script tag not found in the build-docs output (template changed?)')
    const bundlePath = join(root, 'node_modules/redoc/bundles/redoc.standalone.js')
    const bundle = readFileSync(bundlePath)
    const sri = `sha384-${createHash('sha384').update(bundle).digest('base64')}`
    if (sri !== tag[2]) {
      throw new Error(`node_modules/redoc (${sri}) is not the Redoc ${tag[1]} build-docs pins (${tag[2]}): install redoc@${tag[1]}`)
    }
    const js = bundle.toString('utf8')
    if (/<\/script/i.test(js)) throw new Error('Redoc bundle contains "</script": cannot inline safely')
    html = html.replace(tag[0], () => `<script>${js}</script>`)
    if (/<(script|link)[^>]+(src|href)="https?:/i.test(html)) throw new Error('The page still loads an external script or stylesheet')

    html = html.replace('<!DOCTYPE html>', `<!DOCTYPE html>\n<!-- ${BANNER} -->`)
    return html.replace(/\r\n/g, '\n')
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

// --- Markdown ---------------------------------------------------------------------

function resolve(node) {
  let current = node
  const seen = new Set()
  while (current && typeof current.$ref === 'string') {
    if (seen.has(current.$ref)) throw new Error(`$ref cycle at ${current.$ref}`)
    seen.add(current.$ref)
    current = current.$ref.replace(/^#\//, '').split('/').reduce((n, k) => n?.[k], spec)
    if (!current) throw new Error(`Unresolved ${[...seen].pop()}`)
  }
  return current
}
const refName = (ref) => ref.split('/').pop()
const schemaLink = (name) => `[${name}](#schema-${name.toLowerCase()})`
const tagAnchor = (name) => `tag-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`
const opAnchor = (op) => `op-${op.operationId.toLowerCase()}`
const cell = (text) => String(text ?? '').replace(/\|/g, '\\|').replace(/\r?\n+/g, ' ')

function typeOf(schema, depth = 0) {
  if (!schema) return 'any'
  if (schema.$ref) return schemaLink(refName(schema.$ref))
  if (schema.const !== undefined) return `\`${JSON.stringify(schema.const)}\``
  if (schema.oneOf || schema.anyOf) return (schema.oneOf ?? schema.anyOf).map((s) => typeOf(s, depth + 1)).join(' \\| ')
  if (schema.allOf) return schema.allOf.map((s) => typeOf(s, depth + 1)).join(' & ')
  if (schema.enum) return schema.enum.map((v) => `\`${JSON.stringify(v)}\``).join(' \\| ')
  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : []
  const render = (t) => {
    if (t === 'array') return `${typeOf(schema.items, depth + 1)}[]`
    if (t === 'object' && !schema.properties && schema.additionalProperties && schema.additionalProperties !== true) {
      return `map<string, ${typeOf(schema.additionalProperties, depth + 1)}>`
    }
    return t
  }
  return types.length ? types.map(render).join(' \\| ') : 'any'
}

/** Object properties, merged through allOf (for field tables). */
function propertiesOf(schema) {
  const s = resolve(schema)
  if (s.allOf) {
    const merged = { properties: {}, required: [] }
    for (const part of s.allOf) {
      const p = propertiesOf(part)
      Object.assign(merged.properties, p.properties)
      merged.required.push(...p.required)
    }
    return merged
  }
  return { properties: s.properties ?? {}, required: s.required ?? [] }
}

function isInlineObject(schema) {
  return schema && !schema.$ref && (schema.properties || schema.allOf) && !schema.oneOf && !schema.anyOf
}

function fieldRows(schema, prefix = '', depth = 0) {
  const { properties, required } = propertiesOf(schema)
  const rows = []
  for (const [name, prop] of Object.entries(properties)) {
    const path = `${prefix}${name}`
    const optional = !required.includes(name)
    const desc = [prop.description, prop.default !== undefined ? `Default \`${JSON.stringify(prop.default)}\`.` : '']
      .filter(Boolean).join(' ')
    rows.push(`| \`${path}\` | ${typeOf(prop)} | ${optional ? '' : 'yes'} | ${cell(desc)} |`)
    if (depth < 3 && isInlineObject(prop)) rows.push(...fieldRows(prop, `${path}.`, depth + 1))
    if (depth < 3 && prop.type === 'array' && isInlineObject(prop.items)) rows.push(...fieldRows(prop.items, `${path}[].`, depth + 1))
  }
  return rows
}

function fieldTable(schema) {
  const rows = fieldRows(schema)
  if (rows.length === 0) return []
  return ['| Field | Type | Required | Description |', '|---|---|---|---|', ...rows]
}

/** A deterministic example value for a schema (explicit examples win). */
function sample(schema, depth = 0, stack = []) {
  if (!schema || depth > 8) return null
  if (schema.$ref) {
    if (stack.includes(schema.$ref)) return {}
    return sample(resolve(schema), depth, [...stack, schema.$ref])
  }
  if (schema.example !== undefined) return schema.example
  if (Array.isArray(schema.examples) && schema.examples.length) return schema.examples[0]
  if (schema.const !== undefined) return schema.const
  if (schema.default !== undefined) return schema.default
  if (schema.enum) return schema.enum[0]
  if (schema.oneOf || schema.anyOf) return sample((schema.oneOf ?? schema.anyOf)[0], depth + 1, stack)
  if (schema.allOf) {
    return Object.assign({}, ...schema.allOf.map((s) => sample(s, depth + 1, stack)).filter((v) => v && typeof v === 'object'))
  }
  const type = Array.isArray(schema.type) ? schema.type.find((t) => t !== 'null') : schema.type
  switch (type) {
    case 'string': return schema.format === 'date-time' ? '2026-01-01T00:00:00.000Z' : 'string'
    case 'integer': return schema.minimum ?? 0
    case 'number': return 0
    case 'boolean': return true
    case 'array': return schema.items ? [sample(schema.items, depth + 1, stack)] : []
    case 'object': {
      if (!schema.properties) return {}
      return Object.fromEntries(Object.entries(schema.properties).map(([k, v]) => [k, sample(v, depth + 1, stack)]))
    }
    default: return null
  }
}

function exampleOf(media) {
  if (!media) return undefined
  if (media.example !== undefined) return media.example
  if (media.examples) return Object.values(media.examples)[0]?.value
  return sample(media.schema)
}

const jsonBlock = (value) => ['```json', JSON.stringify(value, null, 2), '```']

function paramRows(params) {
  return params.map((p) => {
    const param = resolve(p)
    return `| \`${param.name}\` | ${param.in} | ${typeOf(param.schema)} | ${param.required ? 'yes' : ''} | ${cell(param.description)} |`
  })
}

function responseCodeText(code, response) {
  const r = resolve(response)
  const media = r.content && Object.values(r.content)[0]
  const type = media?.schema ? typeOf(media.schema) : '—'
  return `| ${code} | ${type} | ${cell(r.description)} |`
}

function buildMarkdown() {
  const out = []
  const ops = []
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const method of METHODS) if (item[method]) ops.push({ path, method, op: item[method], item })
  }
  out.push(`<!-- ${BANNER} -->`, '')
  out.push(`# ${spec.info.title} reference`, '')
  out.push(`Version ${spec.info.version} · OpenAPI ${spec.openapi} · ${ops.length} operations · base URL \`${spec.servers[0].url}\``, '')
  out.push('Generated from [openapi.json](openapi.json) (also served by the daemon at `GET /openapi.json`). The interactive version is [api-reference.html](api-reference.html).', '')
  out.push(spec.info.description, '')

  out.push('## Contents', '')
  for (const tag of spec.tags) {
    const tagged = ops.filter((o) => o.op.tags[0] === tag.name)
    out.push(`- [${tag.name}](#${tagAnchor(tag.name)}) (${tagged.length})`)
  }
  out.push('- [Schemas](#schemas)', '')

  for (const tag of spec.tags) {
    const tagged = ops.filter((o) => o.op.tags[0] === tag.name)
    out.push(`<a id="${tagAnchor(tag.name)}"></a>`, '', `## ${tag.name}`, '', tag.description, '')
    out.push('| Method | Path | Summary |', '|---|---|---|')
    for (const { path, method, op } of tagged) out.push(`| ${method.toUpperCase()} | [\`${path}\`](#${opAnchor(op)}) | ${cell(op.summary)} |`)
    out.push('')
    for (const { path, method, op, item } of tagged) {
      out.push(`<a id="${opAnchor(op)}"></a>`, '', `### ${method.toUpperCase()} \`${path}\``, '', `**${op.summary}**`, '')
      if (op.description) out.push(op.description, '')
      const open = Array.isArray(op.security) && op.security.length === 0
      out.push(`Operation \`${op.operationId}\` · ${open ? 'no authentication' : 'bearer token'}`, '')

      const params = [...(item.parameters ?? []), ...(op.parameters ?? [])]
      if (params.length) {
        out.push('**Parameters**', '', '| Name | In | Type | Required | Description |', '|---|---|---|---|---|', ...paramRows(params), '')
      }

      if (op.requestBody) {
        const body = resolve(op.requestBody)
        const media = body.content['application/json']
        out.push(`**Request body** (${body.required ? 'required' : 'optional'}): ${typeOf(media.schema)}`, '')
        if (body.description) out.push(body.description, '')
        const schema = resolve(media.schema)
        if (!schema.oneOf && !schema.anyOf) out.push(...fieldTable(media.schema), '')
        out.push(...jsonBlock(exampleOf(media)), '')
      }

      out.push('**Responses**', '', '| Status | Body | Description |', '|---|---|---|')
      for (const [code, response] of Object.entries(op.responses)) out.push(responseCodeText(code, response))
      out.push('')
      const [okCode, okResponse] = Object.entries(op.responses).find(([code]) => code.startsWith('2'))
      const okMedia = resolve(okResponse).content && Object.entries(resolve(okResponse).content)[0]
      if (okMedia) {
        out.push(`Example ${okCode} (\`${okMedia[0]}\`):`, '', ...jsonBlock(exampleOf(okMedia[1])), '')
      }
    }
  }

  out.push('<a id="schemas"></a>', '', '## Schemas', '')
  out.push('Reusable shapes referenced above. Error bodies share [ErrorResponse](#schema-errorresponse).', '')
  for (const [name, schema] of Object.entries(spec.components.schemas)) {
    out.push(`<a id="schema-${name.toLowerCase()}"></a>`, '', `### ${name}`, '')
    if (schema.description) out.push(schema.description, '')
    const table = fieldTable(schema)
    if (table.length && !schema.oneOf && !schema.anyOf) out.push(...table, '')
    else out.push(`Type: ${typeOf({ ...schema, description: undefined })}`, '')
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}

writeFileSync(mdPath, buildMarkdown())
writeFileSync(htmlPath, buildHtml())
console.log(`Wrote ${rel(mdPath)} and ${rel(htmlPath)}`)
